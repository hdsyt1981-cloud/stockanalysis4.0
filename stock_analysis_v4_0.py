def get_stock_name(symbol: str) -> str:
    """KRX 리스트에서 종목코드에 해당하는 한국어 기업명을 찾아 반환합니다."""
    try:
        df_krx = fdr.StockListing("KRX")
        match = df_krx[df_krx["Code"].astype(str) == str(symbol).strip()]
        if not match.empty:
            return str(match.iloc[0]["Name"])
    except Exception:
        pass
    # US 등 비한국 종목은 이름 조회가 안 될 수 있으므로 티커 자체를 사용합니다.
    return str(symbol).strip().upper() or "지정 종목"


def get_currency_code(symbol: str) -> str:
    """종목 코드 형식으로 표시 통화를 판별합니다: 한국 종목은 KRW, 그 외는 USD.

    한국 종목 예: 005930, 035420, 005930.KS, 035420.KQ, KRX:005930
    미국 종목 예: NVDA, AAPL, BRK.B
    """
    code = str(symbol).strip().upper().replace(" ", "")
    if (re.fullmatch(r"\d{6}", code)
            or re.fullmatch(r"\d{6}\.(?:KS|KQ|KOSPI|KOSDAQ)", code)
            or re.fullmatch(r"KRX:\d{6}", code)):
        return "KRW"
    return "USD"


def get_currency_label(symbol: str) -> str:
    """Readable currency label for reports and charts."""
    return "KRW (원)" if get_currency_code(symbol) == "KRW" else "USD ($)"


def format_price(value, symbol: str) -> str:
    """Format a price according to the selected ticker's market currency."""
    try:
        value = float(value)
    except (TypeError, ValueError):
        return "계산 불가"
    if not np.isfinite(value):
        return "계산 불가"
    if get_currency_code(symbol) == "KRW":
        return f"{value:,.0f}원"
    return f"${value:,.2f}"

def compute_features(raw: pd.DataFrame) -> pd.DataFrame:
    if raw is None or raw.empty:
        raise ValueError("주가 데이터가 비어 있습니다.")
    df = raw.copy().sort_index()
    df = df[~df.index.duplicated(keep="last")]
    required = {"Open", "High", "Low", "Close", "Volume"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"필수 OHLCV 열이 없습니다: {sorted(missing)}")
    for col in required:
        df[col] = pd.to_numeric(df[col], errors="coerce")
    df = df[(df["Close"] > 0) & (df["Open"] > 0) & (df["High"] > 0) & (df["Low"] > 0)]
    close, volume = df["Close"], df["Volume"].clip(lower=0)

    delta = close.diff()
    gain = delta.clip(lower=0).ewm(alpha=1/14, min_periods=14, adjust=False).mean()
    loss = (-delta.clip(upper=0)).ewm(alpha=1/14, min_periods=14, adjust=False).mean()
    rs = gain / loss.replace(0, np.nan)
    rsi = 100 - 100 / (1 + rs)
    rsi = rsi.mask((loss == 0) & (gain > 0), 100.0)
    rsi = rsi.mask((gain == 0) & (loss > 0), 0.0)
    df["RSI_14"] = rsi.fillna(50.0)

    ema20 = close.ewm(span=20, min_periods=20, adjust=False).mean()
    df["Disparity_EMA20"] = close / ema20 - 1
    df["EMA20_Slope_5"] = ema20 / ema20.shift(5) - 1
    ma20, sd20 = close.rolling(20).mean(), close.rolling(20).std(ddof=0)
    upper, lower = ma20 + 2*sd20, ma20 - 2*sd20
    df["BB_Lower"] = lower
    df["BB_Mid"] = ma20
    df["BB_Upper"] = upper
    df["BB_Pct"] = (close - lower) / (upper - lower).replace(0, np.nan)
    # Visualization-only indicators. These are deliberately NOT added to FEATURES.
    df["SMA20"] = close.rolling(20, min_periods=20).mean()
    df["SMA50"] = close.rolling(50, min_periods=50).mean()
    df["SMA200"] = close.rolling(200, min_periods=200).mean()
    df["Volume_MA20"] = volume.rolling(20, min_periods=20).mean()

    prev_close = close.shift(1)
    true_range = pd.concat([
        df["High"] - df["Low"],
        (df["High"] - prev_close).abs(),
        (df["Low" ] - prev_close).abs(),
    ], axis=1).max(axis=1)
    tr_values = true_range.to_numpy(dtype=float)
    atr_values = np.full(len(df), np.nan, dtype=float)
    period = 14
    if len(df) >= period:
        first_window = tr_values[:period]
        if np.isfinite(first_window).all():
            atr_values[period - 1] = float(np.mean(first_window))
            for i in range(period, len(df)):
                if np.isfinite(tr_values[i]) and np.isfinite(atr_values[i - 1]):
                    atr_values[i] = (atr_values[i - 1] * (period - 1) + tr_values[i]) / period
    df["ATR_14"] = atr_values
    df["Swing_Low_20"] = df["Low"].rolling(20, min_periods=20).min()
    logret = np.log(close).diff()
    df["Volatility_20"] = logret.rolling(20).std(ddof=0)
    for n in (5, 10, 20):
        df[f"Ret_{n}"] = close / close.shift(n) - 1
    volmean = volume.rolling(20).mean()
    df["Volume_Ratio_20"] = volume / volmean.replace(0, np.nan)
    df["Range_Pct"] = (df["High"] - df["Low"]) / close
    df["Dist_High_20"] = close / df["High"].rolling(20).max() - 1
    df["Dist_High_60"] = close / df["High"].rolling(60).max() - 1
    df.replace([np.inf, -np.inf], np.nan, inplace=True)
    return df

def _pct_to_fraction(value: float, field_name: str) -> float:
    """Convert a user-entered percentage (e.g. 0.05 means 0.05%) into a fraction."""
    value = float(value)
    if not np.isfinite(value) or value < 0 or value > 20:
        raise ValueError(f"{field_name}는 0~20% 범위의 숫자로 입력해 주세요.")
    return value / 100.0


def _net_return_after_costs(entry_price: float, exit_price: float,
                            fee_pct: float, slippage_pct: float) -> float:
    """Apply adverse slippage to each fill and commission to each side exactly once."""
    fee = _pct_to_fraction(fee_pct, "매매수수료")
    slip = _pct_to_fraction(slippage_pct, "슬리피지")
    if entry_price <= 0 or exit_price <= 0:
        return np.nan
    effective_buy_cost = entry_price * (1.0 + slip) * (1.0 + fee)
    effective_sell_proceeds = exit_price * (1.0 - slip) * (1.0 - fee)
    return effective_sell_proceeds / effective_buy_cost - 1.0


def barrier_outcome(df: pd.DataFrame, signal_i: int, target_pct: float, atr_signal: float,
                    max_holding: int, fee_pct: float, slippage_pct: float,
                    atr_multiple: float = 2.0) -> BarrierResult:
    """Label by gross market-price barriers; report strategy return after costs."""
    n = len(df)
    if signal_i + 1 >= n:
        return BarrierResult(np.nan, pd.NaT, np.nan, "unresolved", np.nan, np.nan)
    if not np.isfinite(target_pct) or target_pct <= 0:
        raise ValueError("목표 수익률은 0%보다 커야 합니다.")
    if int(max_holding) < 1:
        raise ValueError("최대 보유 기간은 1거래일 이상이어야 합니다.")
    # Validate costs even when this example happens to resolve early.
    _pct_to_fraction(fee_pct, "매매수수료")
    _pct_to_fraction(slippage_pct, "슬리피지")

    entry_i = signal_i + 1
    entry = float(df["Open"].iloc[entry_i])
    if not np.isfinite(entry) or entry <= 0:
        return BarrierResult(np.nan, pd.NaT, np.nan, "unresolved", np.nan, np.nan)
    target = entry * (1 + target_pct / 100.0)
    if not np.isfinite(atr_signal) or atr_signal <= 0:
        return BarrierResult(np.nan, pd.NaT, np.nan, "invalid_atr", entry, np.nan)
    stop = entry - float(atr_multiple) * float(atr_signal)
    if not np.isfinite(stop) or stop <= 0 or stop >= entry:
        return BarrierResult(np.nan, pd.NaT, np.nan, "invalid_stop", entry, np.nan)

    last_i = min(entry_i + int(max_holding) - 1, n - 1)
    full_horizon = (last_i - entry_i + 1 == int(max_holding))
    exit_price, exit_reason, exit_i = np.nan, "unresolved", None
    for j in range(entry_i, last_i + 1):
        op, hi, lo = (float(df[c].iloc[j]) for c in ("Open", "High", "Low"))
        # Gap exits are filled at the open, which is more conservative than target/stop level.
        if op >= target:
            exit_price, exit_reason, exit_i = op, "target_gap", j
            break
        if op <= stop:
            exit_price, exit_reason, exit_i = op, "stop_gap", j
            break
        hit_target, hit_stop = hi >= target, lo <= stop
        if hit_target and hit_stop:
            exit_price, exit_reason, exit_i = stop, "both_hit_stop_first", j
            break
        if hit_target:
            exit_price, exit_reason, exit_i = target, "target", j
            break
        if hit_stop:
            exit_price, exit_reason, exit_i = stop, "stop", j
            break

    if exit_i is None:
        if not full_horizon:
            return BarrierResult(np.nan, pd.NaT, np.nan, "unresolved", entry, np.nan)
        exit_i = last_i
        exit_price = float(df["Close"].iloc[exit_i])
        exit_reason = "time_exit"

    net = _net_return_after_costs(entry, float(exit_price), fee_pct, slippage_pct)
    # Classification label asks whether the gross price target was hit before the stop.
    label = 1.0 if exit_reason.startswith("target") else 0.0
    return BarrierResult(label, pd.Timestamp(df.index[exit_i]), float(exit_price), exit_reason,
                         entry, float(net))


def structural_stop_prices(features_df: pd.DataFrame, atr_multiple: float = 2.0) -> pd.Series:
    """Signal-day close reference stop. Backtest stop is based on next-session entry open."""
    close = features_df["Close"].astype(float)
    atr = features_df["ATR_14"].astype(float)
    stop = close - float(atr_multiple) * atr
    stop = stop.where((stop > 0) & (stop < close))
    return stop.rename("Stop_Price_Signal")


def build_labeled_data(features_df: pd.DataFrame, target_pct: float, atr_multiple: float,
                       max_holding: int, fee_pct: float, slippage_pct: float) -> pd.DataFrame:
    df = features_df.copy()
    stop_prices = structural_stop_prices(df, atr_multiple)
    labels, t1, entries, exits, reasons, net_returns, stop_distances = [], [], [], [], [], [], []
    for i in range(len(df)):
        atr_value = float(df["ATR_14"].iloc[i]) if pd.notna(df["ATR_14"].iloc[i]) else np.nan
        r = barrier_outcome(df, i, target_pct, atr_value, max_holding,
                            fee_pct, slippage_pct, atr_multiple)
        labels.append(r.label); t1.append(r.t1); entries.append(r.entry_price)
        exits.append(r.exit_price); reasons.append(r.exit_reason); net_returns.append(r.net_return)
        if np.isfinite(r.entry_price) and r.entry_price > 0 and np.isfinite(atr_value) and atr_value > 0:
            actual_stop = r.entry_price - atr_multiple * atr_value
            stop_distances.append(round((actual_stop / r.entry_price - 1) * 100, 2))
        else:
            stop_distances.append(np.nan)
    df["Stop_Price_Signal"] = stop_prices
    df["Stop_Distance_Pct"] = stop_distances
    df["Label"] = labels
    df["t1"] = pd.to_datetime(t1)
    df["Entry_Open"] = entries
    df["Exit_Price"] = exits
    df["Exit_Reason"] = reasons
    df["Net_Return"] = net_returns
    return df

def make_xgb(y: pd.Series) -> XGBClassifier:
    positives = int((y == 1).sum())
    negatives = int((y == 0).sum())
