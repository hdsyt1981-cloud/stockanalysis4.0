def download_report_force(filename):
    if not os.path.exists(filename):
        print(f"오류: 파일이 존재하지 않습니다. ({filename})")
        return
    print(f"파일 [{filename}] 다운로드를 시도합니다...")
    try:
        from google.colab import files as colab_files
        colab_files.download(filename)
    except Exception:
        print("표준 다운로드 실패, 우회 스크립트를 시도합니다...")
        with open(filename, "rb") as f:
            data = f.read()
        b64 = base64.b64encode(data).decode()
        js_script = f"""<script>
            var link = document.createElement('a');
            link.href = 'data:application/vnd.openxmlformats-officedocument.wordprocessingml.document;base64,{b64}';
            link.download = '{filename}';
            document.body.appendChild(link); link.click(); document.body.removeChild(link);
        </script>"""
        display(HTML(js_script))
        print("브라우저 전송 완료.")

