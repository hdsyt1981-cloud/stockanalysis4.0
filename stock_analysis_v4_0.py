def backtest_summary(test_df: pd.DataFrame, scores: np.ndarray, threshold: float,
                    price_df: Optional[pd.DataFrame] = None,
                    fee_pct: float = 0.05, slippage_pct: float = 0.15) -> dict:
    """Single-position sequential backtest; trade statistics are only executed, non-overlapping trades."""
    empty = {
        "총진입신호수": 0, "비중복거래수": 0, "원래발생한신호수": 0,
        "겹침으로제외한신호수": 0, "기타제외신호수": 0,
        "수익거래수": 0, "손실거래수": 0, "목표달성거래수": 0,
        "목표달성률_실제거래_%": np.nan,
        "평균손익_%_성공율": np.nan, "평균순수익률_%": np.nan,
        "실제승률_%": np.nan, "중앙값수익_%": np.nan,
        "평균수익거래_%": np.nan, "평균손실거래_%": np.nan,
        "손익비_합산기준": np.nan,
        "CAGR": np.nan, "MDD": np.nan, "칼마비율": np.nan,
        "평가기간_시작": None, "평가기간_종료": None,
        "전략_초기자산": 1.0, "전략_최종자산": np.nan, "전략_누적수익률_%": np.nan,
        "동일평가기간_주가보유수익률_%": np.nan, "동일평가기간_주가보유CAGR_%": np.nan,
        "MDD_기준": "일별 포트폴리오 자산곡선(보유 중 비용 반영 청산가 기준 평가)",
        "거래없음": True,
    }
    if price_df is None:
        price_df = test_df
    if test_df is None or test_df.empty or price_df is None or price_df.empty:
        return empty
    _pct_to_fraction(fee_pct, "매매수수료")
    _pct_to_fraction(slippage_pct, "슬리피지")
    price_df = price_df.sort_index()
    test_df = test_df.sort_index()
    if len(scores) != len(test_df):
        raise ValueError("백테스트 점수 수와 평가 데이터 행 수가 다릅니다.")

    score_arr = np.asarray(scores, dtype=float)
    selected_mask = np.isfinite(score_arr) & (score_arr >= threshold)
    selected = test_df.loc[selected_mask].copy()
    selected = selected[selected["Net_Return"].notna() & selected["t1"].notna() &
                        selected["Entry_Open"].notna() & selected["Exit_Price"].notna()]
    empty["원래발생한신호수"] = int(len(selected))
    empty["평가기간_시작"] = pd.Timestamp(test_df.index.min()).strftime("%Y-%m-%d")
    empty["평가기간_종료"] = pd.Timestamp(test_df.index.max()).strftime("%Y-%m-%d")
    if selected.empty:
        empty.update(_same_period_buy_hold_metrics(price_df, test_df.index.min(), test_df.index.max()))
        return empty

    calendar = pd.DatetimeIndex(price_df.index)
    accepted = []
    last_exit = pd.Timestamp.min
    overlap_excluded = 0
    other_excluded = 0
    for signal_date, row in selected.iterrows():
        loc = calendar.get_indexer([pd.Timestamp(signal_date)])[0]
        if loc < 0 or loc + 1 >= len(calendar):
            other_excluded += 1
            continue
        entry_date = pd.Timestamp(calendar[loc + 1])
        exit_date = pd.Timestamp(row["t1"])
        if entry_date <= last_exit:
            overlap_excluded += 1
            continue
        if exit_date < entry_date or entry_date not in price_df.index or exit_date not in price_df.index:
            other_excluded += 1
            continue
        entry_price, exit_price = float(row["Entry_Open"]), float(row["Exit_Price"])
        net_return = _net_return_after_costs(entry_price, exit_price, fee_pct, slippage_pct)
        if not (np.isfinite(entry_price) and entry_price > 0 and np.isfinite(exit_price) and
                exit_price > 0 and np.isfinite(net_return) and net_return > -1):
            other_excluded += 1
            continue
        exit_reason = str(row.get("Exit_Reason", ""))
        accepted.append((pd.Timestamp(signal_date), entry_date, exit_date,
                         float(net_return), entry_price, exit_price, exit_reason))
        last_exit = exit_date

    empty["겹침으로제외한신호수"] = int(overlap_excluded)
    empty["기타제외신호수"] = int(other_excluded)
    if not accepted:
        empty.update(_same_period_buy_hold_metrics(price_df, test_df.index.min(), test_df.index.max()))
        return empty

    period_start = min(x[0] for x in accepted)
    period_end = max(x[2] for x in accepted)
    dates = calendar[(calendar >= period_start) & (calendar <= period_end)]
    fee = _pct_to_fraction(fee_pct, "매매수수료")
    slip = _pct_to_fraction(slippage_pct, "슬리피지")
    equity_values = []
    cash_equity = 1.0
    trade_idx = 0
    active = None
    active_capital = None
    for day in dates:
        day = pd.Timestamp(day)
        if active is None and trade_idx < len(accepted) and accepted[trade_idx][1] == day:
            active = accepted[trade_idx]
            active_capital = cash_equity
        if active is not None:
            signal_date, entry_date, exit_date, net_return, entry_price, exit_price, exit_reason = active
            if day >= exit_date:
                cash_equity = active_capital * (1.0 + net_return)
                equity_values.append(cash_equity)
                active = None
                active_capital = None
                trade_idx += 1
            else:
                close_price = float(price_df.at[day, "Close"])
                if np.isfinite(close_price) and close_price > 0:
                    effective_buy_cost = entry_price * (1 + slip) * (1 + fee)
                    estimated_liquidation = close_price * (1 - slip) * (1 - fee)
                    marked = active_capital * estimated_liquidation / effective_buy_cost
                    equity_values.append(marked if np.isfinite(marked) and marked > 0 else active_capital)
                else:
                    equity_values.append(active_capital)
        else:
            equity_values.append(cash_equity)

    equity = pd.Series(equity_values, index=dates, dtype=float).replace([np.inf, -np.inf], np.nan).dropna()
    if equity.empty or (equity <= 0).any():
        mdd = np.nan
        cagr = np.nan
    else:
        peaks = equity.cummax()
        mdd = abs(float((equity / peaks - 1.0).min()))
        years = max((equity.index[-1] - equity.index[0]).days / 365.25, 1 / 365.25)
        cagr = float((equity.iloc[-1] / 1.0) ** (1.0 / years) - 1.0)
    calmar = cagr / mdd if np.isfinite(cagr) and np.isfinite(mdd) and mdd > 0 else np.nan
    rets = np.asarray([x[3] for x in accepted], dtype=float)
    pos = rets[rets > 0]
    neg = rets[rets <= 0]
    target_count = sum(1 for x in accepted if x[6].startswith("target"))
    mean_return = float(np.mean(rets) * 100.0) if len(rets) else np.nan
    mean_win = float(np.mean(pos) * 100.0) if len(pos) else np.nan
    mean_loss = float(np.mean(neg) * 100.0) if len(neg) else np.nan
    profit_factor = (float(np.sum(pos) / abs(np.sum(neg))) if len(neg) and abs(np.sum(neg)) > 0
                     else (float("inf") if len(pos) and not len(neg) else np.nan))
    benchmark_metrics = _same_period_buy_hold_metrics(price_df, period_start, period_end)
    final_equity = float(equity.iloc[-1]) if not equity.empty and np.isfinite(equity.iloc[-1]) else np.nan
    return {
        "총진입신호수": int(len(rets)),
        "비중복거래수": int(len(rets)),
        "원래발생한신호수": int(len(selected)),
        "겹침으로제외한신호수": int(overlap_excluded),
        "기타제외신호수": int(other_excluded),
        "수익거래수": int((rets > 0).sum()),
        "손실거래수": int((rets <= 0).sum()),
        "목표달성거래수": int(target_count),
        "목표달성률_실제거래_%": round(float(target_count / len(rets) * 100.0), 2) if len(rets) else np.nan,
        "평균손익_%_성공율": round(mean_return, 3) if np.isfinite(mean_return) else np.nan,
        "평균순수익률_%": round(mean_return, 3) if np.isfinite(mean_return) else np.nan,
        "실제승률_%": round(float((rets > 0).mean() * 100.0), 2) if len(rets) else np.nan,
        "중앙값수익_%": round(float(np.median(rets) * 100.0), 3) if len(rets) else np.nan,
        "평균수익거래_%": round(mean_win, 3) if np.isfinite(mean_win) else np.nan,
        "평균손실거래_%": round(mean_loss, 3) if np.isfinite(mean_loss) else np.nan,
        "손익비_합산기준": round(profit_factor, 3) if np.isfinite(profit_factor) else ("무한대" if np.isinf(profit_factor) else np.nan),
        "CAGR": round(cagr * 100, 2) if np.isfinite(cagr) else np.nan,
        "MDD": round(mdd * 100, 2) if np.isfinite(mdd) else np.nan,
        "칼마비율": round(calmar, 3) if np.isfinite(calmar) else np.nan,
        "평가기간_시작": period_start.strftime("%Y-%m-%d"),
        "평가기간_종료": period_end.strftime("%Y-%m-%d"),
        "전략_초기자산": 1.0,
        "전략_최종자산": round(final_equity, 6) if np.isfinite(final_equity) else np.nan,
        "전략_누적수익률_%": round((final_equity - 1.0) * 100.0, 2) if np.isfinite(final_equity) else np.nan,
        **benchmark_metrics,
        "MDD_기준": "일별 포트폴리오 자산곡선(보유 중 비용 반영 청산가 기준 평가)",
        "거래없음": False,
    }

