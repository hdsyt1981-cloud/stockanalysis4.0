def _trend_assessment(features_df: pd.DataFrame) -> tuple[str, str]:
    """Explain current price regime using only observations through the latest date."""
    if features_df is None or len(features_df) < 60:
        return "데이터 부족으로 판단 유보", "추세 판단에 필요한 과거 가격 데이터가 충분하지 않습니다."
    last = features_df.iloc[-1]
    close = float(last.get("Close", np.nan))
    ema20 = float(last.get("Disparity_EMA20", np.nan))
    sma50 = float(last.get("SMA50", np.nan))
    sma200 = float(last.get("SMA200", np.nan)) if pd.notna(last.get("SMA200", np.nan)) else np.nan
    rsi = float(last.get("RSI_14", np.nan))
    ret5 = float(last.get("Ret_5", np.nan))
    slope20 = float(last.get("EMA20_Slope_5", np.nan))
    if not all(np.isfinite(x) for x in [close, ema20, sma50, rsi, ret5, slope20]):
        return "데이터 부족으로 판단 유보", "필수 추세 지표 중 계산할 수 없는 값이 있습니다."
    above_ema = ema20 >= 0  # Disparity_EMA20 is relative distance to EMA20.
    above_sma50 = close >= sma50
    long_up = np.isfinite(sma200) and close >= sma200
    if above_sma50 and above_ema and slope20 > 0:
        state = "상승 추세"
        reason = "종가가 EMA20·SMA50 위에 있고 EMA20의 최근 기울기도 상승 방향입니다."
        if np.isfinite(sma200) and not long_up:
            state = "단기 상승·장기 추세 혼조"
            reason += " 다만 종가는 SMA200 아래에 있어 장기 추세는 아직 혼조입니다."
    elif not above_sma50 and not above_ema and slope20 < 0:
        state = "하락 추세"
        reason = "종가가 EMA20·SMA50 아래에 있고 EMA20의 최근 기울기도 하락 방향입니다."
    elif not above_sma50 and above_ema and ret5 > 0:
        state = "하락 이후 반등 시도"
        reason = "최근 5거래일 수익률이 플러스이고 종가가 EMA20 위로 올라왔지만 SMA50 아래에 있습니다. 추세 전환 확정은 아닙니다."
    elif abs(close / sma50 - 1) <= 0.03 and abs(slope20) < 0.01:
        state = "횡보 또는 방향성 불명확"
        reason = "종가가 SMA50 근처에 있고 EMA20의 최근 기울기가 크지 않습니다."
    elif above_sma50 and slope20 < 0:
        state = "상승 추세 중 조정 가능성"
        reason = "종가는 SMA50 위에 있지만 EMA20의 최근 기울기가 하락 방향입니다."
    else:
        state = "혼조·방향성 불명확"
        reason = "가격과 이동평균선의 신호가 일치하지 않아 단일 추세로 판단하기 어렵습니다."
    if rsi >= 70:
        reason += " RSI는 70 이상으로 단기 과열 가능성이 있으나, 단독 매도 신호는 아닙니다."
    elif rsi <= 30:
        reason += " RSI는 30 이하로 침체 구간이지만, 단독 매수 신호는 아닙니다."
    return state, reason


def create_stock_charts(features_df: pd.DataFrame, symbol: str, signal_dates=None,
                        output_dir: Optional[Path] = None) -> dict:
    """Create long-history and recent candlestick/indicator charts."""
    if output_dir is None:
        output_dir = Path.cwd()
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    safe_symbol = re.sub(r"[^A-Za-z0-9._-]+", "_", str(symbol)) or "stock"
    currency_code = get_currency_code(symbol)
    currency_label = get_currency_label(symbol)
    from matplotlib.ticker import FuncFormatter
    if currency_code == "KRW":
        price_formatter = FuncFormatter(lambda value, _position: f"{value:,.0f}")
        price_axis_label = "주가 (KRW, 원)"
        atr_axis_label = "ATR (KRW, 원)"
    else:
        price_formatter = FuncFormatter(lambda value, _position: f"${value:,.2f}")
        price_axis_label = "주가 (USD, $)"
        atr_axis_label = "ATR (USD, $)"
    data = features_df.sort_index().copy()
    data = data[~data.index.duplicated(keep="last")]
    if data.empty:
        raise ValueError("차트를 만들 가격 데이터가 없습니다.")
    long_path = output_dir / f"{safe_symbol}_v3_4_long_chart.png"
    recent_path = output_dir / f"{safe_symbol}_v3_4_recent_chart.png"

    # Long-term view: all available history; visualization-only moving averages.
    fig, ax = plt.subplots(figsize=(14, 6.5))
    ax.plot(data.index, data["Close"], label="Close", linewidth=1.0)
    for col, label in [("SMA50", "SMA 50"), ("SMA200", "SMA 200")]:
        if col in data and data[col].notna().any():
            ax.plot(data.index, data[col], label=label, linewidth=1.0)
    if "BB_Upper" in data and "BB_Lower" in data:
        ax.fill_between(data.index, data["BB_Lower"].to_numpy(dtype=float),
                        data["BB_Upper"].to_numpy(dtype=float), alpha=0.12, label="Bollinger Band")
    ax.set_title(f"{symbol} · 장기 주가 흐름 ({currency_label}) · {data.index[0]:%Y-%m-%d} – {data.index[-1]:%Y-%m-%d}")
    ax.set_ylabel(price_axis_label)
    ax.yaxis.set_major_formatter(price_formatter)
    ax.grid(True, alpha=0.25)
    ax.legend(loc="best", ncol=4)
    ax.xaxis.set_major_locator(mdates.AutoDateLocator())
    ax.xaxis.set_major_formatter(mdates.ConciseDateFormatter(ax.xaxis.get_major_locator()))
    fig.tight_layout()
    fig.savefig(long_path, dpi=140, bbox_inches="tight")
    plt.close(fig)

    # Recent view: candle + Bollinger/averages, RSI, volume, ATR.
    recent = data.tail(min(250, len(data))).copy()
    xdates = mdates.date2num(pd.DatetimeIndex(recent.index).to_pydatetime())
    fig, axes = plt.subplots(4, 1, figsize=(14, 12), sharex=True,
                             gridspec_kw={"height_ratios": [5, 1.5, 1.5, 1.4]})
    axp, axr, axv, axa = axes
    if len(xdates) > 1:
        candle_width = max(0.25, float(np.median(np.diff(xdates))) * 0.65)
    else:
        candle_width = 0.6
    for x, (_, row) in zip(xdates, recent.iterrows()):
        try:
            op, hi, lo, cl = [float(row[c]) for c in ("Open", "High", "Low", "Close")]
        except Exception:
            continue
        if not np.isfinite([op, hi, lo, cl]).all():
            continue
        up = cl >= op
        candle_color = "#d62728" if up else "#1f77b4"
        axp.vlines(x, lo, hi, color=candle_color, linewidth=0.8)
        body_bottom = min(op, cl)
        body_height = max(abs(cl - op), max(abs(cl), 1.0) * 0.0005)
        axp.add_patch(Rectangle((x - candle_width / 2, body_bottom), candle_width, body_height,
                                facecolor=candle_color, edgecolor=candle_color, linewidth=0.5, alpha=0.85))
    for col, label, lw in [("BB_Upper", "BB Upper", 0.8), ("BB_Mid", "BB Mid", 0.8),
                           ("BB_Lower", "BB Lower", 0.8), ("Disparity_EMA20", "", 0)]:
        if col.startswith("BB_") and col in recent and recent[col].notna().any():
            axp.plot(recent.index, recent[col], label=label, linewidth=lw, alpha=0.8)
    for col, label, lw in [("SMA20", "SMA 20", 1.0), ("SMA50", "SMA 50", 1.1), ("SMA200", "SMA 200", 1.1)]:
        if col in recent and recent[col].notna().any():
            axp.plot(recent.index, recent[col], label=label, linewidth=lw)
    if signal_dates is not None:
        valid_signal_dates = [pd.Timestamp(d) for d in signal_dates if pd.Timestamp(d) in recent.index]
        if valid_signal_dates:
            axp.scatter(valid_signal_dates, recent.loc[valid_signal_dates, "Close"],
                        marker="^", s=55, label="Historical model signal", zorder=5)
    axp.set_title(f"{symbol} · 최근 상세 차트 ({currency_label}) · {recent.index[0]:%Y-%m-%d} – {recent.index[-1]:%Y-%m-%d}")
    axp.set_ylabel(price_axis_label)
    axp.yaxis.set_major_formatter(price_formatter)
    axp.grid(True, alpha=0.22)
    axp.legend(loc="best", ncol=4, fontsize=8)

    axr.plot(recent.index, recent["RSI_14"], label="RSI 14", linewidth=1.0)
    for level in [30, 50, 70]:
        axr.axhline(level, linestyle="--", linewidth=0.8, alpha=0.65)
    axr.set_ylim(0, 100)
    axr.set_ylabel("RSI")
    axr.grid(True, alpha=0.2)
    axr.legend(loc="upper left")

    volume = recent["Volume"].fillna(0).clip(lower=0)
    candle_colors = ["#d62728" if c >= o else "#1f77b4" for o, c in zip(recent["Open"], recent["Close"])]
    axv.bar(recent.index, volume, color=candle_colors, width=0.7, alpha=0.65, label="Volume")
    if recent["Volume_MA20"].notna().any():
        axv.plot(recent.index, recent["Volume_MA20"], label="Volume MA20", linewidth=1.0)
    axv.set_ylabel("Volume")
    axv.grid(True, alpha=0.2)
    axv.legend(loc="upper left")

    axa.plot(recent.index, recent["ATR_14"], label="ATR 14", linewidth=1.0)
    axa.set_ylabel(atr_axis_label)
    axa.yaxis.set_major_formatter(price_formatter)
    axa.grid(True, alpha=0.2)
    axa.legend(loc="upper left")
    axa.xaxis.set_major_locator(mdates.AutoDateLocator())
    axa.xaxis.set_major_formatter(mdates.ConciseDateFormatter(axa.xaxis.get_major_locator()))
    fig.tight_layout()
    fig.savefig(recent_path, dpi=140, bbox_inches="tight")
    plt.close(fig)
    return {"long": str(long_path), "recent": str(recent_path)}


def walk_forward_oof(development: pd.DataFrame, n_folds: int = 5,
                     initial_fraction: float = 0.45) -> list[dict]:
    """Expanding-window OOF predictions. Training labels must resolve before each test fold."""
    out = []
    if development is None or len(development) < 70:
        return out
    n = len(development)
    first_test = max(50, int(n * initial_fraction))
    if first_test >= n - 2:
        return out
    edges = np.linspace(first_test, n, n_folds + 1, dtype=int)
    for fold_no in range(n_folds):
        a, b = int(edges[fold_no]), int(edges[fold_no + 1])
        if b <= a:
            continue
        test = development.iloc[a:b].copy()
        if test.empty:
            continue
        test_start = pd.Timestamp(test.index[0])
        train = development[(development.index < test_start) &
                            (pd.to_datetime(development["t1"]) < test_start)].copy()
        train = train[train[FEATURES].notna().all(axis=1) & train["Label"].notna()]
        if len(train) < 30 or train["Label"].nunique() < 2:
            continue
        try:
            model = _fit_xgb(train)
            scores = model.predict_proba(test[FEATURES])[:, 1]
        except Exception as exc:
            print(f"워크포워드 fold {fold_no + 1} 계산을 건너뜁니다: {exc}")
            continue
        train_positive_n = int((train["Label"].astype(int) == 1).sum())
        train_start = pd.Timestamp(train.index.min()) if len(train) else pd.NaT
        train_end = pd.Timestamp(train.index.max()) if len(train) else pd.NaT
        for date, label, score in zip(test.index, test["Label"].astype(int).to_numpy(), scores):
            out.append({"date": pd.Timestamp(date), "label": int(label),
                        "score": float(score), "fold": int(fold_no + 1),
                        "train_n": int(len(train)), "train_positive_n": train_positive_n,
                        "train_start": train_start, "train_end": train_end,
                        "test_start": test_start,
                        "t1": pd.Timestamp(test.at[date, "t1"])})
    return out


def _fold_metrics_table(oof: pd.DataFrame, threshold: float) -> list[dict]:
    rows = []
    if oof is None or oof.empty:
        return rows
    for fold, frame in oof.groupby("fold", sort=True):
        y, scores = frame["label"].to_numpy(dtype=int), frame["score"].to_numpy(dtype=float)
        metrics = metrics_report(y, scores, threshold, f"워크포워드 {fold}차")
        metrics["학습표본수"] = int(frame["train_n"].max())
        metrics["학습실제급등사례수"] = int(frame["train_positive_n"].max()) if "train_positive_n" in frame else np.nan
        metrics["검증실제급등사례수"] = int((frame["label"].astype(int) == 1).sum())
        metrics["학습시작"] = pd.to_datetime(frame["train_start"]).min().strftime("%Y-%m-%d") if "train_start" in frame else ""
        metrics["학습종료"] = pd.to_datetime(frame["train_end"]).max().strftime("%Y-%m-%d") if "train_end" in frame else ""
        metrics["검증시작"] = frame["date"].min().strftime("%Y-%m-%d")
        metrics["검증종료"] = frame["date"].max().strftime("%Y-%m-%d")
        metrics["구간번호"] = int(fold)
        rows.append(metrics)
    return rows


